// Generates api/_madeInPlaces.json — the country/region vocabulary the
// server-side /made-in renderer needs.
//
// Why generated rather than hand-written in api/: the API deploys separately
// from the frontend (see .github/workflows — api/** ships via "Deploy
// tabarnam-xai-dedicated"), so it cannot import src/lib/madeInSlugs.js at
// runtime. A hand-kept second copy of the slug rules would drift, and drift
// here means the server renders a canonical URL that the client router
// redirects away from — the worst possible signal to send a crawler.
//
// The output IS committed: the API build doesn't run this script. CI should
// run `node scripts/generate-made-in-places.mjs --check` to prove the
// committed file still matches the source of truth.
//
// Usage:
//   node scripts/generate-made-in-places.mjs
//   node scripts/generate-made-in-places.mjs --check   (exit 1 if stale)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  countryDisplayName,
  countrySlug,
  regionSlug,
  SLUG_ALIASES,
  US_REGIONS,
} from "../src/lib/madeInSlugs.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const COUNTRIES = path.join(ROOT, "public", "geo", "countries.json");
const OUT = path.join(ROOT, "api", "_madeInPlaces.json");
const CHECK = process.argv.includes("--check");

const countries = JSON.parse(fs.readFileSync(COUNTRIES, "utf8"))
  .map(({ code, name }) => ({ cc: String(code || "").toUpperCase(), isoName: name }))
  .filter(({ cc, isoName }) => /^[A-Z]{2}$/.test(cc) && isoName)
  .map(({ cc, isoName }) => ({
    cc,
    slug: countrySlug(cc, isoName),
    // The name the page shows in its <h1> and <title> — "USA", not the ISO
    // "United States". Must match what MadeInPage.jsx renders or the
    // server HTML and the hydrated HTML disagree on the headline.
    name: countryDisplayName(cc, isoName),
  }))
  .sort((a, z) => a.cc.localeCompare(z.cc));

const usRegions = US_REGIONS.map(([code, name]) => ({
  code,
  slug: regionSlug(code, name),
  name,
}));

const payload = {
  _comment:
    "GENERATED by scripts/generate-made-in-places.mjs from public/geo/countries.json + src/lib/madeInSlugs.js. Do not edit by hand.",
  countries,
  usRegions,
  // Alias slug → canonical slug. The renderer 301s these rather than serving
  // duplicate content, matching the client router's <Navigate replace>.
  aliases: SLUG_ALIASES,
};

const json = `${JSON.stringify(payload, null, 2)}\n`;

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== json) {
    console.error(
      "[generate-made-in-places] api/_madeInPlaces.json is STALE. Run `node scripts/generate-made-in-places.mjs` and commit the result."
    );
    process.exit(1);
  }
  console.log("[generate-made-in-places] api/_madeInPlaces.json is up to date.");
  process.exit(0);
}

fs.writeFileSync(OUT, json, "utf8");
console.log(
  `[generate-made-in-places] wrote api/_madeInPlaces.json (${countries.length} countries, ${usRegions.length} US regions, ${Object.keys(SLUG_ALIASES).length} aliases)`
);
